def _entry_id(source: Path) -> str:
    return hashlib.sha256(os.fsencode(source)).hexdigest()[:16]


def _runtime(
    entries: tuple[tuple[Path, Path], ...],
    *,
    named: tuple[tuple[str, str, tuple[tuple[str, Path, Path], ...]], ...] = (),
    default: str = "all-media",
    extra_top_level: str = "",
) -> str:
    lines = [
        "# Generated by Wall-in-One. Edit the library in the app, not this file.",
        "schema_version = 2",
        f'default_playlist = "{default}"',
        extra_top_level,
        "",
        "[settings]",
        "cycle_interval_seconds = 300",
        "cycle_enabled = false",
        "shuffle = false",
        "dynamics_enabled = true",
        "",
        "[renderer]",
        'noctalia_program = "/usr/bin/noctalia"',
        'niri_program = "/usr/bin/niri"',
        'mpvpaper_program = "/usr/bin/mpvpaper"',
        'linux_wallpaperengine_program = "/usr/bin/linux-wallpaperengine"',
        "own_scene_renderer = true",
        'layer = "background"',
        'video_when_hidden = "pause"',
        "video_hardware_decode = true",
        "video_muted = true",
        "video_volume = 100",
        "scene_fps = 30",
        "scene_muted = true",
        "scene_volume = 100",
        "scene_pause_when_covered = true",
        'scene_scaling = ""',
        'scene_clamp = ""',
        "",
        "[[playlists]]",
        'id = "all-media"',
        'name = "All media"',
    ]
    for source, capture in entries:
        lines.extend(
            (
                "",
                "[[playlists.entries]]",
                f'id = "{_entry_id(source)}"',
                'kind = "video"',
                f"still = {json.dumps(str(capture))}",
                f"motion = {json.dumps(str(source))}",
                'palette = { kind = "keep", mode = "keep" }',
            )
        )
    for identifier, name, authored_entries in named:
        lines.extend(("", "[[playlists]]", f'id = "{identifier}"', f'name = "{name}"'))
        for entry_id, source, capture in authored_entries:
            lines.extend(
                (
                    "",
                    "[[playlists.entries]]",
                    f'id = "{entry_id}"',
                    'kind = "video"',
                    f"still = {json.dumps(str(capture))}",
                    f"motion = {json.dumps(str(source))}",
                    'palette = { kind = "keep", mode = "keep" }',
                )
            )
    return "\n".join(line for line in lines if line != extra_top_level or line) + "\n"


def _profile(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    *,
    videos: int = 1,
    named_playlist: bool = False,
) -> _Profile:
    home = tmp_path / "home"
    config_home = tmp_path / "config"
    state_home = tmp_path / "state"
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setenv("XDG_CONFIG_HOME", str(config_home))
    monkeypatch.setenv("XDG_STATE_HOME", str(state_home))
    root = home / "wallpapers"
    automatic = root / "Wall-in-One" / "Automatic Stills"
    automatic.mkdir(parents=True)
    entries: list[tuple[Path, Path]] = []
    for ordinal in range(videos):
        source = root / f"clip-{ordinal}.mp4"
        capture = automatic / f"clip-{ordinal}.png"
        source.write_bytes(f"video-{ordinal}".encode())
        capture.write_bytes(b"\x89PNG\r\n\x1a\n" + bytes([ordinal]))
        entries.append((source, capture))
    marker = {
        "schema": 1,
        "plugin": "goober/wall-in-one",
        "kind": "automatic-stills",
        "ownership": "managed",
    }
    marker_path = automatic / ".managed-by-wall-in-one-v1.json"
    marker_path.write_text(json.dumps(marker) + "\n", encoding="utf-8")

    paths.settings_path().parent.mkdir(parents=True)
    active = "saved" if named_playlist else ""
    paths.settings_path().write_text(_old_settings(active_playlist=active), encoding="utf-8")
    paths.noctalia_settings_path().parent.mkdir(parents=True)
    paths.noctalia_settings_path().write_text(
        "[unrelated]\n"
        'directory = "/must/not/be-used"\n\n'
        "[wallpaper]\n"
        f"directory = {json.dumps(str(root))}\n",
        encoding="utf-8",
    )

    named: tuple[tuple[str, str, tuple[tuple[str, Path, Path], ...]], ...] = ()
    if named_playlist:
        source, capture = entries[0]
        saved = playlists.Playlist(
            id="saved",
            name="Saved",
            entries=(playlists.Entry(id="entry-a", source=str(source)),),
        )
        playlists.save({saved.id: saved})
        named = (("saved", "Saved", (("entry-a", source, capture),)),)
    paths.runtime_config_path().parent.mkdir(parents=True, exist_ok=True)
    paths.runtime_config_path().write_text(
        _runtime(tuple(entries), named=named, default=active or "all-media"),
        encoding="utf-8",
    )
    return _Profile(root, automatic, tuple(entries), marker_path)


