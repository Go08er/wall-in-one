"""One-way, no-overwrite import from the retired Noctalia Luau plugin.

The 0.x Noctalia plugin and this application share a name but not a storage
format.  The plugin kept its authoring document below Noctalia's plugin data
directory, while this application deliberately splits settings, pairings,
playlists, schedules and display assignments into app-owned XDG files.

Migration is conservative for three reasons:

* the legacy bytes are never edited or deleted, so rolling back is possible;
* an import only starts when every current authoring target is absent; and
* each target is installed with a no-replace hard link from a same-directory
  stage.  A small journal makes an interrupted multi-file install resumable
  without accepting a mixture of old and newly generated bytes.

This module has no GTK dependency.  The CLI and the first-run GUI use the same
probe and transaction rather than maintaining two subtly different upgrades.
"""

