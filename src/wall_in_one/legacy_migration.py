@dataclass(frozen=True, slots=True)
class _LegacySource:
    directory: Path
    config_path: Path
    runtime_path: Path
    settings_path: Path
    config: dict[str, Any]
    runtime: dict[str, Any]
    plugin_settings: dict[str, Any]
    config_bytes: bytes
    runtime_bytes: bytes
    settings_bytes: bytes
    schema: int

    @property
    def digest(self) -> str:
        digest = hashlib.sha256()
        for document in (self.config_bytes, self.runtime_bytes, self.settings_bytes):
            digest.update(len(document).to_bytes(8, "big"))
            digest.update(document)
        return digest.hexdigest()


