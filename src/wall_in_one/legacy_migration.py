class MigrationError(Exception):
    """Legacy authoring could not be imported without guessing or overwriting."""


@dataclass(frozen=True, slots=True)
class Probe:
    status: ProbeStatus
    detail: str
    source: Path
    schema: int | None = None
    playlists: int = 0
    outputs: int = 0
    conflicts: tuple[Path, ...] = ()

    @property
    def needs_decision(self) -> bool:
        return self.status in ("ready", "conflict", "corrupt", "in-progress")


