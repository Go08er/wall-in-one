def _existing_authoring() -> tuple[Path, ...]:
    found: list[Path] = []
    # An orphaned report is not authoring, but it is an install target.  Treat
    # it as a conflict up front instead of discovering it after linking part of
    # a new profile.
    for target in (*_authoring_targets(), report_path()):
        try:
            target.lstat()
        except FileNotFoundError:
            continue
        except OSError:
            # An unreadable directory entry is still a conflict.  Import must
            # never reinterpret inability to inspect a target as absence.
            found.append(target)
        else:
            found.append(target)
    return tuple(found)


def _marker_document() -> dict[str, Any] | None:
    target = marker_path()
    try:
        raw = file_io.read_regular_bytes(target, MAX_JOURNAL_BYTES)
    except OSError as error:
        raise MigrationError(f"cannot safely read migration marker {target}: {error}") from error
    if raw is None:
        return None
    document = _json_object(raw, target)
    if type(document.get("version")) is not int or document["version"] != MIGRATION_VERSION:
        raise MigrationError(f"migration marker {target} has an unsupported format")
    disposition = document.get("disposition")
    if disposition not in ("imported", "declined"):
        raise MigrationError(f"migration marker {target} has no valid disposition")
    if disposition == "imported":
        _validate_imported_marker(document, target)
    else:
        _validate_declined_marker(document, target)
    return document


def _validate_imported_marker(document: dict[str, Any], target: Path) -> None:
    required_fields = {
        "version",
        "disposition",
        "legacy_source",
        "legacy_schema",
        "legacy_digest",
        "imported_at",
        "legacy_bytes_modified",
        "report",
        "targets",
    }
    if set(document) != required_fields:
        raise MigrationError(f"imported migration marker {target} is incomplete or ambiguous")
    _recorded_path(document["legacy_source"], "imported marker legacy source")
    schema = document["legacy_schema"]
    if type(schema) is not int or schema not in (1, 2, 3, 4, 5):
        raise MigrationError(f"imported migration marker {target} has an invalid legacy schema")
    _sha256(document["legacy_digest"], "imported marker legacy digest")
    _timestamp(document["imported_at"], "imported marker timestamp")
    if document["legacy_bytes_modified"] is not False:
        raise MigrationError(
            f"imported migration marker {target} does not preserve the legacy source"
        )
    if _recorded_path(document["report"], "imported marker report") != report_path():
        raise MigrationError(f"imported migration marker {target} names a different report")

    raw_targets = document["targets"]
    if not isinstance(raw_targets, dict):
        raise MigrationError(f"imported migration marker {target} has no target manifest")
    names = set(raw_targets)
    allowed = _IMPORTED_REQUIRED_TARGETS | _IMPORTED_OPTIONAL_TARGETS
    if not _IMPORTED_REQUIRED_TARGETS <= names <= allowed:
        raise MigrationError(
            f"imported migration marker {target} has an incomplete target manifest"
        )
    expected_paths = _imported_target_paths()
    for name, raw_entry in raw_targets.items():
        if not isinstance(name, str) or not isinstance(raw_entry, dict):
            raise MigrationError(f"imported migration marker {target} has an invalid target entry")
        if set(raw_entry) != {"path", "sha256"}:
            raise MigrationError(
                f"imported migration marker {target} target {name!r} is incomplete or ambiguous"
            )
        recorded = _recorded_path(raw_entry["path"], f"imported marker target {name!r}")
        if recorded != expected_paths[name]:
            raise MigrationError(
                f"imported migration marker {target} target {name!r} names a different path"
            )
        _sha256(raw_entry["sha256"], f"imported marker target {name!r} digest")

    # Digests describe the immutable completion snapshot, not a permanent pin:
    # normal authoring replaces these files after import.  Their identities
    # must remain present and safe, however, or a bare/forged marker could turn
    # a missing migration into an apparent success.  Clearing a credential is
    # a supported mutation, so an absent optional key remains valid.
    maximums = _imported_target_maximums()
    for name in sorted(names):
        path = expected_paths[name]
        try:
            present = _safe_regular_presence(path, maximums[name])
        except OSError as error:
            raise MigrationError(
                f"imported migration target {name!r} at {path} is not safely readable: {error}"
            ) from error
        if not present and name in _IMPORTED_REQUIRED_TARGETS:
            raise MigrationError(f"imported migration target {name!r} is missing at {path}")


def _validate_declined_marker(document: dict[str, Any], target: Path) -> None:
    required_fields = {
        "version",
        "disposition",
        "legacy_source",
        "legacy_config",
        "legacy_config_sha256",
        "legacy_schema",
        "recorded_at",
        "legacy_bytes_modified",
    }
    if set(document) != required_fields:
        raise MigrationError(f"declined migration marker {target} is incomplete or ambiguous")
    source = _recorded_path(document["legacy_source"], "declined marker legacy source")
    legacy_config = _recorded_path(document["legacy_config"], "declined marker legacy config")
    if legacy_config != source / LEGACY_CONFIG_FILENAME:
        raise MigrationError(f"declined migration marker {target} names a different config")
    _sha256(document["legacy_config_sha256"], "declined marker config digest")
    schema = document["legacy_schema"]
    if schema is not None and (
        type(schema) is not int or not -MAX_RECORDED_SCHEMA_ABS <= schema <= MAX_RECORDED_SCHEMA_ABS
    ):
        raise MigrationError(f"declined migration marker {target} has an invalid legacy schema")
    _timestamp(document["recorded_at"], "declined marker timestamp")
    if document["legacy_bytes_modified"] is not False:
        raise MigrationError(
            f"declined migration marker {target} does not preserve the legacy source"
        )


