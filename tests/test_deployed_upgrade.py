def test_exact_pinned_capture_sizes_enforce_total_before_hashing(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    profile = _profile(tmp_path, monkeypatch, videos=2)
    first_capture = profile.entries[0][1]
    second_capture = profile.entries[1][1]
    first_capture.write_bytes(b"aaaa")
    second_capture.write_bytes(b"bbbb")
    replacement = tmp_path / "replacement-capture"
    replacement.write_bytes(b"bbbbbbbb")
    monkeypatch.setattr(deployed_upgrade, "MAX_CAPTURE_BYTES", 16)
    monkeypatch.setattr(deployed_upgrade, "MAX_TOTAL_CAPTURE_BYTES", 10)

    original_pin = deployed_upgrade._pin_capture
    replaced = False

    def replace_after_observed_prescan(
        stack: contextlib.ExitStack,
        directory: file_io.PinnedDirectoryContext,
        source: Path,
        capture: Path,
        source_pin: file_io.PinnedPath,
        source_fingerprint: file_io.FileFingerprint,
        *,
        prior_capture_bytes: int,
    ) -> tuple[deployed_upgrade.CapturePlan, file_io.PinnedPath]:
        nonlocal replaced
        if not replaced:
            os.replace(replacement, second_capture)
            replaced = True
        return original_pin(
            stack,
            directory,
            source,
            capture,
            source_pin,
            source_fingerprint,
            prior_capture_bytes=prior_capture_bytes,
        )

    original_hash = file_io.hash_pinned_regular
    hashed: list[str] = []

    def record_hash(
        pinned: file_io.PinnedPath,
        *,
        expected_fingerprint: file_io.FileFingerprint | None = None,
        maximum_bytes: int | None = None,
    ) -> tuple[int, str]:
        hashed.append(pinned.path.name)
        return original_hash(
            pinned,
            expected_fingerprint=expected_fingerprint,
            maximum_bytes=maximum_bytes,
        )

    monkeypatch.setattr(deployed_upgrade, "_pin_capture", replace_after_observed_prescan)
    monkeypatch.setattr(file_io, "hash_pinned_regular", record_hash)

    found = deployed_upgrade.probe()

    assert replaced
    assert found.status == "corrupt"
    assert "total bound" in found.detail
    assert hashed == [first_capture.name]


