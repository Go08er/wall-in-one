def test_exact_profile_builds_generation_bound_read_only_plan(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    profile = _profile(tmp_path, monkeypatch, videos=2, named_playlist=True)
    before = {
        path: path.read_bytes()
        for path in (
            paths.settings_path(),
            paths.runtime_config_path(),
            paths.noctalia_settings_path(),
            profile.marker,
        )
    }
    found = deployed_upgrade.probe()
    plan = deployed_upgrade.build_plan()
    assert found.status == "ready"
    assert found.counts == deployed_upgrade.UpgradeCounts(
        videos=2,
        captures=2,
        all_media_entries=2,
        playlists=1,
        playlist_entries=1,
        schedules=0,
    )
    assert plan.root == profile.root
    assert plan.automatic_stills == profile.automatic
    assert tuple(evidence.kind for evidence in plan.authoring_evidence) == (
        "pairings",
        "playlists",
        "schedules",
        "displays",
        "favourites",
        "pending-removals",
    )
    present_evidence = [evidence for evidence in plan.authoring_evidence if evidence.present]
    assert len(present_evidence) == 1
    assert present_evidence[0].kind == "playlists"
    assert present_evidence[0].fingerprint == file_io.file_fingerprint(
        playlists.state_path().lstat()
    )
    assert (
        present_evidence[0].sha256
        == hashlib.sha256(playlists.state_path().read_bytes()).hexdigest()
    )
    assert all(
        evidence.fingerprint is None and evidence.sha256 is None
        for evidence in plan.authoring_evidence
        if not evidence.present
    )
    assert len(plan.captures) == 2
    for capture in plan.captures:
        assert capture.dynamic_id == f"video:{capture.source_path}"
        assert capture.capture_size == capture.capture_fingerprint[2]
        assert (
            capture.capture_sha256 == hashlib.sha256(capture.capture_path.read_bytes()).hexdigest()
        )
    assert before == {path: path.read_bytes() for path in before}
    assert not deployed_upgrade.journal_path().exists()
    assert not deployed_upgrade.completion_path().exists()


